const used = new Set<string>();
// some operation ids repeat across the Support API (UpdateAttributeValue for skills and for routing): the later one
// gets a number
const name: AppConfig["name"] = (id, method, path, op) => {
  let n = named(id, method, path, op);
  for (let i = 2; used.has(n); i++) n = `${id}${i}`;
  used.add(n);
  return n;
};

